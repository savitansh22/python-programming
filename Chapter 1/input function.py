#input()statement is used to accept values from user.

#string input
name = input("name: ")

#int input
age = int(input("age: "))

#float input
balance = float(input("balance: "))

print(f"name: {name}, age: {age}, Balance: {balance}")
#f " " before the quote tells python that this is a formatted string.
#{variables} anything you put inside the curly braces will be evaluted as code and replaced with the actual value stored in that variable.